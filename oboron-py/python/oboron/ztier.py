Zmock1Hex = getattr(_oboron, "Zmock1Hex", None)

# Utility functions (re-exported here for ergonomics — the canonical
# import path is `from oboron import generate_secret`).
generate_secret = _oboron.generate_secret
generate_secret_bytes = _oboron.generate_secret_bytes


